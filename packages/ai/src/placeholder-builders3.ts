import { ideaOf, list, sourcesOf, str, type Ctx, type StubBuilder } from './placeholder-context.js';

export const synthesisBuilders: Record<string, StubBuilder> = {
  thesis(ctx: Ctx) {
    const i = ideaOf(ctx);
    const sources = sourcesOf(ctx);
    const assumptions = list<Ctx>(ctx.assumptions);
    const contradictions = list<Ctx>(ctx.contradictions);
    const unknowns = list<string>(ctx.unknowns);
    const critical = assumptions.filter((a) => str(a.criticality) === 'CRITICAL');
    return {
      opportunity: `An opportunity to serve ${i.customer} with ${i.solution}. Generated by the placeholder provider; configure a real model for production research.`,
      customer: i.customer,
      problem: i.problem,
      existingBehavior: `Today ${i.customer} appear to rely on manual workarounds and generic tools; this is unverified.`,
      proposedSolution: i.solution,
      evidenceSummary: `${sources.length} source(s) were retrieved and catalogued. Evidence is predominantly low-tier and does not yet establish willingness to pay.`,
      criticalAssumptions: (critical.length ? critical : assumptions).slice(0, 5).map((a) => ({
        statement: str(a.statement, 'Assumption'),
        criticality: str(a.criticality, 'HIGH'),
        evidenceState: str(a.evidenceState, 'UNKNOWN'),
      })),
      contradictoryEvidence: contradictions.map((c) =>
        str(c.contradictingStatement, 'Counter-evidence recorded.'),
      ),
      unknowns: unknowns.length
        ? unknowns
        : ['Whether the target customer will pay the proposed price remains unresolved.'],
      competitiveEnvironment:
        'Competition exists across direct, indirect and substitute categories; non-consumption is a live possibility and was explicitly searched for.',
      economics:
        'Unit economics cannot be established from desk research alone; CAC and retention are unknown.',
      feasibility: 'FEASIBLE_WITH_ENGINEERING',
      marketSize: [
        {
          label: 'TAM',
          value: 'UNKNOWN',
          methodology: 'Not estimated — insufficient authoritative inputs retrieved.',
          inputs: [],
          source: null,
          date: null,
          geography: i.geography,
          population: i.customer,
          assumptions: ['Requires a bottom-up estimate before any number is shown.'],
        },
      ],
      economicsModel: [
        { label: 'Price', value: i.pricing ?? 'UNKNOWN', basis: i.pricing ? 'ASSUMPTION' : 'UNKNOWN', source: null },
        { label: 'CAC', value: 'UNKNOWN', basis: 'UNKNOWN', source: null },
        { label: 'Retention', value: 'UNKNOWN', basis: 'UNKNOWN', source: null },
        { label: 'Gross margin', value: 'ASSUMPTION', basis: 'ASSUMPTION', source: null },
      ],
      recommendedNextStep: 'Run 15 customer interviews and offer a paid pilot at the proposed price.',
    };
  },

  quality_check(ctx: Ctx) {
    const sourceCount = typeof ctx.sourceCount === 'number' ? ctx.sourceCount : 0;
    const counterCount = typeof ctx.counterCount === 'number' ? ctx.counterCount : 0;
    const unsupported = list<Ctx>(ctx.unsupportedClaims).map((c) => ({
      statement: str(c.statement, 'Unsupported claim'),
      reason: str(c.reason, 'No supporting source.'),
    }));
    let overall: 'PASSED' | 'PASSED_WITH_WARNINGS' | 'FAILED' = 'PASSED';
    if (sourceCount === 0) overall = 'FAILED';
    else if (sourceCount < 3 || counterCount === 0) overall = 'PASSED_WITH_WARNINGS';
    return {
      citationCoverage: sourceCount >= 3 ? 'PASS' : 'WARN',
      citationCorrectness: 'PASS',
      freshness: 'WARN',
      contradictionCoverage: counterCount > 0 ? 'PASS' : 'FAIL',
      geographyAlignment: 'WARN',
      numericalConsistency: 'PASS',
      assumptionTransparency: 'PASS',
      hallucination: unsupported.length ? 'FAIL' : 'PASS',
      unsupportedClaims: unsupported,
      overall,
      summary:
        overall === 'PASSED'
          ? 'Quality gate passed.'
          : overall === 'PASSED_WITH_WARNINGS'
            ? 'Report published with warnings: coverage or counter-evidence is limited.'
            : 'Insufficient evidence to publish a complete report.',
    };
  },

  experiment_set(ctx: Ctx) {
    const i = ideaOf(ctx);
    const assumptions = list<Ctx>(ctx.assumptions);
    const priorityBy = (c: string): string =>
      c === 'CRITICAL' ? 'CRITICAL' : c === 'HIGH' ? 'HIGH' : c === 'MEDIUM' ? 'MEDIUM' : 'LOW';
    return {
      experiments: assumptions
        .filter((a) => ['CRITICAL', 'HIGH'].includes(str(a.criticality)))
        .slice(0, 5)
        .map((a, index) => ({
          assumptionIndex: index,
          name: `Validate: ${str(a.statement, 'assumption').slice(0, 60)}`,
          hypothesis: str(a.statement, 'The assumption holds.'),
          method: str(a.requiredExperiment, 'Run a structured real-world test.'),
          targetParticipants: `15 qualified ${i.customer}`,
          successCriterion:
            'At least 3 of 15 qualified prospects take the concrete next step (paid pilot / commitment).',
          failureCriterion: 'No qualified prospect commits after 15 conversations.',
          priority: priorityBy(str(a.criticality)),
        })),
    };
  },
};
